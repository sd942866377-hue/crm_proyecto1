export const DICCIONARIOS: Record<LocalePanel, Record<string, string>> = {
  "es-419": ES419,
  "es-ES": { ...ES419, ...ES_ES_DIFERENCIAS },
  en: EN,
  "pt-BR": PT_BR,
};

export function esLocalePanel(v: unknown): v is LocalePanel {
  return typeof v === "string" && v in LOCALES_PANEL;
}

/**
 * Si el dueño no eligió idioma de panel, se hereda del idioma del BOT: alguien
 * que puso su bot en portugués casi seguro quiere el panel en portugués, y
 * pedirle que lo elija dos veces es fricción sin razón.
 */
export function localePanel(env: Env): LocalePanel {
  const elegido = (env as { PANEL_LANGUAGE?: string }).PANEL_LANGUAGE;
  if (esLocalePanel(elegido)) return elegido;

  const bot = (env.BOT_LANGUAGE || "").trim().toLowerCase();
  if (bot === "es-es" || bot === "es_es") return "es-ES";
  if (bot.startsWith("pt")) return "pt-BR";
  if (bot.startsWith("en")) return "en";
  return "es-419";
}

/** El `t` ya atado a un idioma — para pasarlo a funciones auxiliares. */
export type Traductor = (clave: ClaveI18n) => string;

/** Devuelve el `t` de esta petición. */
export function traductor(env: Env): Traductor {
  const dict = DICCIONARIOS[localePanel(env)];
  return (clave) => dict[clave] ?? ES419[clave] ?? clave;
}

/** Para páginas sin `env` (login, errores): español latino. */
export function traductorNeutro(clave: ClaveI18n): string {
  return ES419[clave] ?? clave;
}

/** El `lang=""` del <html>. Importa para lectores de pantalla y para que el
 *  navegador no ofrezca "traducir esta página" cuando ya está en su idioma. */
export function idiomaHtml(env?: Env): string {
  if (!env) return "es";
  const l = localePanel(env);
  return l === "es-419" ? "es" : l;
}
